# ==============================================================================
# One-Step Company Windows PC Installer
# Domain : https://thietbibachkhoa.id.vn/ (Zero-Hosting Power-Coupled Port 8765)
# TPU    : Kaggle Free TPU v5e-8 / v3-8 (Method 2 - 30h/week Free)
# Storage: 30 TB Google Drive Ultra + Local KeyVault (chmod 600 / NTFS ACL)
# ==============================================================================
param(
    [int]$Port = 8765,
    [string]$Domain = "thietbibachkhoa.id.vn",
    [string]$TunnelToken = "",
    [string]$TpuEndpointUrl = "",
    [string]$GeminiApiKey = "",
    [switch]$NonInteractive
)

$ErrorActionPreference = "Stop"
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$ProjectRoot = Split-Path -Parent $ScriptDir
Set-Location $ProjectRoot

Write-Host "========================================================================" -ForegroundColor Cyan
Write-Host " CAI DAT HE THONG UAV GEOTIFF VN2000 TREN MAY CONG TY (WINDOWS)" -ForegroundColor Cyan
Write-Host " Ten mien : https://$Domain/ -> http://127.0.0.1:$Port" -ForegroundColor Cyan
Write-Host "========================================================================" -ForegroundColor Cyan

# 1. Check Python 3
$PyCmd = Get-Command python -ErrorAction SilentlyContinue
if (-not $PyCmd) {
    $PyCmd = Get-Command py -ErrorAction SilentlyContinue
}
if (-not $PyCmd) {
    Write-Host "[!] Chua tim thay Python. Dang thu cai qua winget..." -ForegroundColor Yellow
    if (Get-Command winget -ErrorAction SilentlyContinue) {
        winget install -e --id Python.Python.3.11 --accept-package-agreements --accept-source-agreements
    } else {
        throw "Vui long cai Python 3.10+ tu https://www.python.org/downloads/ (tich 'Add Python to PATH') roi chay lai."
    }
}

# 2. Initialize KeyVault & 30TB Google Drive config
Write-Host "`n[1/5] Khoi tao KeyVault va cau hinh Kaggle Free TPU..." -ForegroundColor Green
& python -c "from uav_app.infrastructure.gdrive_key_storage import KeyVaultManager; kv = KeyVaultManager(); print('UAV_TPU_API_KEY:', kv.get_masked_status()['keys_configured']['UAV_TPU_API_KEY']['masked'])"

# Load existing config/.env.windows if present so pre-saved Token is preserved
$EnvWinPath = Join-Path $ProjectRoot "config\.env.windows"
$ExistingEnv = @{}
if (Test-Path $EnvWinPath) {
    foreach ($line in Get-Content $EnvWinPath) {
        if ($line -match '^\s*([^#=]+?)\s*=\s*(.+?)\s*$') {
            $ExistingEnv[$matches[1]] = $matches[2]
        }
    }
}
if ([string]::IsNullOrWhiteSpace($TunnelToken) -and $ExistingEnv.ContainsKey("CLOUDFLARE_TUNNEL_TOKEN")) {
    $TunnelToken = $ExistingEnv["CLOUDFLARE_TUNNEL_TOKEN"]
    Write-Host "[OK] Da tim thay Cloudflare Tunnel Token luu san trong config\.env.windows." -ForegroundColor Green
}

if (-not $NonInteractive) {
    if ([string]::IsNullOrWhiteSpace($TunnelToken)) {
        Write-Host "`n[2/5] Nhap Cloudflare Tunnel Token (neu da tao o nha tren dash.cloudflare.com)." -ForegroundColor Yellow
        Write-Host "      (Bo trong va nhan Enter neu ban muon dang nhap Cloudflare bang trinh duyet sau)" -ForegroundColor DarkGray
        $TunnelToken = Read-Host "Cloudflare Tunnel Token (Optional)"
    }
    if ([string]::IsNullOrWhiteSpace($TpuEndpointUrl)) {
        Write-Host "`n[3/5] Nhap URL Kaggle Free TPU (dang https://xxxx.trycloudflare.com neu da chay Kaggle)." -ForegroundColor Yellow
        Write-Host "      (Bo trong va nhan Enter neu chua chay Kaggle ngay luc nay)" -ForegroundColor DarkGray
        $TpuEndpointUrl = Read-Host "Kaggle TPU Endpoint URL (Optional)"
    }
}

# Save config/.env.windows for automatic startup loading
$EnvLines = @(
    "# Auto-generated by setup_company_windows.ps1",
    "UAV_WEB_PORT=$Port",
    "UAV_TPU_PROVIDER=kaggle_free_tpu"
)
if ($ExistingEnv.ContainsKey("CLOUDFLARE_TUNNEL_ID")) {
    $EnvLines += "CLOUDFLARE_TUNNEL_ID=$($ExistingEnv['CLOUDFLARE_TUNNEL_ID'])"
}
if (-not [string]::IsNullOrWhiteSpace($TunnelToken)) {
    $EnvLines += "CLOUDFLARE_TUNNEL_TOKEN=$($TunnelToken.Trim())"
}
if (-not [string]::IsNullOrWhiteSpace($TpuEndpointUrl)) {
    $EnvLines += "UAV_TPU_ENDPOINT_URL=$($TpuEndpointUrl.Trim())"
    & python -c "from uav_app.infrastructure.gdrive_key_storage import KeyVaultManager; KeyVaultManager().set_key('UAV_TPU_ENDPOINT_URL', '$($TpuEndpointUrl.Trim())')"
}
if (-not [string]::IsNullOrWhiteSpace($GeminiApiKey)) {
    $EnvLines += "GEMINI_API_KEY=$($GeminiApiKey.Trim())"
    & python -c "from uav_app.infrastructure.gdrive_key_storage import KeyVaultManager; KeyVaultManager().set_key('GEMINI_API_KEY', '$($GeminiApiKey.Trim())')"
}
Set-Content -Path $EnvWinPath -Value ($EnvLines -join "`r`n") -Encoding UTF8

# 3. Install cloudflared if missing
Write-Host "`n[4/5] Kiem tra va cai dat Cloudflare Tunnel (cloudflared)..." -ForegroundColor Green
if (-not (Get-Command cloudflared -ErrorAction SilentlyContinue)) {
    if (Get-Command winget -ErrorAction SilentlyContinue) {
        winget install -e --id Cloudflare.cloudflared --accept-package-agreements --accept-source-agreements
    } else {
        $CfDir = Join-Path $env:LOCALAPPDATA "cloudflared"
        New-Item -ItemType Directory -Force -Path $CfDir | Out-Null
        $CfExe = Join-Path $CfDir "cloudflared.exe"
        Invoke-WebRequest -Uri "https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-windows-amd64.exe" -OutFile $CfExe
        [Environment]::SetEnvironmentVariable("Path", "$env:Path;$CfDir", "User")
        $env:Path = "$env:Path;$CfDir"
    }
}

# Generate Windows-specific cloudflared YAML fallback
$WinTunnelYaml = Join-Path $ProjectRoot "config\cloudflared_thietbibachkhoa_windows.yml"
$CredsPath = Join-Path $env:USERPROFILE ".cloudflared\uav-thietbibachkhoa-tunnel.json"
& python -c "from uav_app.infrastructure.autostart_host import generate_cloudflared_config; from pathlib import Path; Path(r'$WinTunnelYaml').write_text(generate_cloudflared_config(port=$Port, domain='$Domain', credentials_file=r'$CredsPath'), encoding='utf-8')"

# 4. Register Windows OnStartup + OnLogon Scheduled Task (Machine ON -> Web ON, Machine OFF -> Web OFF)
Write-Host "`n[5/5] Dang ky tu khoi dong cung Windows (Bat may la Web chay, Tat may la Web tat)..." -ForegroundColor Green
& (Join-Path $ScriptDir "install_windows_autostart.ps1") -Port $Port -Domain $Domain

# Start right now and verify local health
Start-Process -FilePath "cmd.exe" -ArgumentList "/c `"$ScriptDir\start_thietbibachkhoa_windows.bat`"" -WorkingDirectory $ProjectRoot -WindowStyle Minimized
Start-Sleep -Seconds 3

try {
    $Health = Invoke-RestMethod -Uri "http://127.0.0.1:$Port/api/health" -TimeoutSec 5
    Write-Host "`n[OK] Web Server dang hoat dong tai http://127.0.0.1:$Port/ (Domain: $($Health.custom_domain_url))" -ForegroundColor Green
} catch {
    Write-Host "`n[!] Da dang ky xong. Khoi dong lai hoac chay start_thietbibachkhoa_windows.bat de kiem tra cong $Port." -ForegroundColor Yellow
}

Write-Host "`nHOAN TAT! Khi may cong ty BAT, https://$Domain/ se tu mo; khi TAT may, web se tu ngat." -ForegroundColor Cyan
